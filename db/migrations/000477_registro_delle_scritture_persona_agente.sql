-- 000477_registro_delle_scritture_persona_agente.sql
-- Piano interfacce, lotto L9, voce A-1 (ADR-0050 D6, ADR-0051 §6; domanda Q9 del piano):
-- «ogni scrittura lascia traccia: chi, per conto di chi (persona o agente), quando, che cosa».
--
-- Fino a qui l'API teneva il registro delle DECISIONI tracciabili (audit.valore_eventi, 000470),
-- cioè delle sole scritture del catalogo andate a buon fine, e l'agente vi compariva solo se il
-- client lo dichiarava in un'intestazione. Questa tabella tiene OGNI scrittura (POST, PUT,
-- PATCH, DELETE su /v1/*) di chi è autenticato, con l'esito HTTP, anche quando è rifiutata: un
-- agente che prova a scrivere fuori dal suo compito resta scritto qui.
--
-- Chi ha agito viene dal token, mai dal corpo né da un'intestazione: un gettone d'agente
-- (`POST /v1/auth/agent-tokens`) porta la persona (`sub`) e l'agente con il suo compito.
-- `persona_user_id` è SEMPRE la persona: chi ha agito (attore persona) o per conto di chi
-- (attore agente).
--
-- Senza chiavi esterne, di proposito: un registro di chi ha fatto che cosa deve sopravvivere
-- alla cancellazione di chi vi compare (la lezione di ADR-0050 D4, migrazione 000475). Nel
-- registro GDPR è ACTOR e RETAIN, come audit.valore_eventi: la persona ne è autrice, non
-- soggetto, e fuori dal fascicolo dell'art. 15.
--
-- Solo aggiunte: un trigger rifiuta UPDATE e DELETE.
--
-- Idempotente: CREATE ... IF NOT EXISTS, CREATE OR REPLACE, ON CONFLICT DO NOTHING.
-- Rollback dichiarato (elenco esplicito):
--   DELETE FROM sys.sys_gdpr_data_map WHERE (gdpr_map_table_schema, gdpr_map_table_name,
--     gdpr_map_subject_fk) = ('audit','registro_scritture','registro_scrittura_persona_user_id');
--   DROP TABLE audit.registro_scritture; DROP FUNCTION audit.f_registro_scritture_solo_aggiunte();

BEGIN;

CREATE TABLE IF NOT EXISTS audit.registro_scritture (
  registro_scrittura_id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  registro_scrittura_tenant_id        uuid,
  registro_scrittura_attore_tipo      varchar(10)  NOT NULL,
  registro_scrittura_persona_user_id  uuid         NOT NULL,
  registro_scrittura_agente_codice    varchar(64),
  registro_scrittura_agente_compito   varchar(200),
  registro_scrittura_gettone_jti      varchar(64),
  registro_scrittura_metodo           varchar(8)   NOT NULL,
  registro_scrittura_rotta            varchar(200) NOT NULL,
  registro_scrittura_stato_http       smallint     NOT NULL,
  registro_scrittura_richiesta_id     varchar(64),
  registro_scrittura_dettaglio        jsonb,
  registro_scrittura_avvenuta_il      timestamptz  NOT NULL DEFAULT now()
);

COMMENT ON TABLE audit.registro_scritture IS
  '000477 (piano interfacce L9, A-1) — registro solo-aggiunte di ogni scrittura su /v1/* di chi è '
  'autenticato: chi (persona o agente), per conto di chi, quando, che cosa, con quale esito. '
  'L''identità viene dal token; per un agente, dal gettone di POST /v1/auth/agent-tokens.';
COMMENT ON COLUMN audit.registro_scritture.registro_scrittura_persona_user_id IS
  'Sempre la persona: chi ha agito (attore persona) o per conto di chi (attore agente). Senza FK: il registro sopravvive alla cancellazione.';

-- I vincoli fuori dal CREATE TABLE, in forma DROP/ADD: la catena si riapplica a ogni deploy.
ALTER TABLE audit.registro_scritture DROP CONSTRAINT IF EXISTS registro_scritture_attore_ck;
ALTER TABLE audit.registro_scritture ADD CONSTRAINT registro_scritture_attore_ck
  CHECK (registro_scrittura_attore_tipo IN ('persona', 'agente'));
ALTER TABLE audit.registro_scritture DROP CONSTRAINT IF EXISTS registro_scritture_metodo_ck;
ALTER TABLE audit.registro_scritture ADD CONSTRAINT registro_scritture_metodo_ck
  CHECK (registro_scrittura_metodo IN ('POST', 'PUT', 'PATCH', 'DELETE'));
ALTER TABLE audit.registro_scritture DROP CONSTRAINT IF EXISTS registro_scritture_agente_ck;
ALTER TABLE audit.registro_scritture ADD CONSTRAINT registro_scritture_agente_ck
  CHECK (
    (registro_scrittura_attore_tipo = 'agente')
      = (registro_scrittura_agente_codice IS NOT NULL AND registro_scrittura_agente_compito IS NOT NULL)
  );
ALTER TABLE audit.registro_scritture DROP CONSTRAINT IF EXISTS registro_scritture_stato_ck;
ALTER TABLE audit.registro_scritture ADD CONSTRAINT registro_scritture_stato_ck
  CHECK (registro_scrittura_stato_http BETWEEN 100 AND 599);

CREATE INDEX IF NOT EXISTS idx_registro_scritture_tenant_istante
  ON audit.registro_scritture (registro_scrittura_tenant_id, registro_scrittura_avvenuta_il);
CREATE INDEX IF NOT EXISTS idx_registro_scritture_persona_istante
  ON audit.registro_scritture (registro_scrittura_persona_user_id, registro_scrittura_avvenuta_il);
CREATE INDEX IF NOT EXISTS idx_registro_scritture_agenti
  ON audit.registro_scritture (registro_scrittura_agente_codice, registro_scrittura_avvenuta_il)
  WHERE registro_scrittura_attore_tipo = 'agente';

-- Solo aggiunte.
CREATE OR REPLACE FUNCTION audit.f_registro_scritture_solo_aggiunte() RETURNS trigger
LANGUAGE plpgsql AS $fn$
BEGIN
  RAISE EXCEPTION 'audit.registro_scritture accetta solo aggiunte (%): il registro di chi ha scritto non si corregge',
    TG_OP USING ERRCODE = 'insufficient_privilege';
END;
$fn$;

DROP TRIGGER IF EXISTS trg_registro_scritture_solo_aggiunte ON audit.registro_scritture;
CREATE TRIGGER trg_registro_scritture_solo_aggiunte
  BEFORE UPDATE OR DELETE ON audit.registro_scritture
  FOR EACH ROW EXECUTE FUNCTION audit.f_registro_scritture_solo_aggiunte();

INSERT INTO sys.sys_gdpr_data_map (
  gdpr_map_table_schema, gdpr_map_table_name, gdpr_map_subject_fk,
  gdpr_map_data_class, gdpr_map_erasure_strategy, gdpr_map_reference_kind,
  gdpr_map_legal_basis
) VALUES
  ('audit', 'registro_scritture', 'registro_scrittura_persona_user_id',
   'OPERATIONAL', 'RETAIN', 'ACTOR',
   'Registro di ogni scrittura con chi l''ha fatta e per conto di chi, persona o agente (L9, A-1): '
   'accountability. La persona ne è autrice, l''oggetto può riguardare altri: fuori dal fascicolo art. 15.')
ON CONFLICT (gdpr_map_table_schema, gdpr_map_table_name, gdpr_map_subject_fk) DO NOTHING;

DO $post$
DECLARE
  n_ck int;
  n_gdpr int;
BEGIN
  SELECT count(*) INTO n_ck FROM pg_constraint
   WHERE conrelid = 'audit.registro_scritture'::regclass
     AND conname IN ('registro_scritture_attore_ck', 'registro_scritture_metodo_ck',
                     'registro_scritture_agente_ck', 'registro_scritture_stato_ck');
  IF n_ck <> 4 THEN
    RAISE EXCEPTION '000477: vincoli del registro delle scritture % su 4', n_ck;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_trigger
                  WHERE tgrelid = 'audit.registro_scritture'::regclass
                    AND tgname = 'trg_registro_scritture_solo_aggiunte' AND NOT tgisinternal) THEN
    RAISE EXCEPTION '000477: manca il trigger solo-aggiunte';
  END IF;
  SELECT count(*) INTO n_gdpr FROM sys.sys_gdpr_data_map
   WHERE gdpr_map_table_schema = 'audit' AND gdpr_map_table_name = 'registro_scritture'
     AND gdpr_map_subject_fk = 'registro_scrittura_persona_user_id' AND gdpr_map_reference_kind = 'ACTOR';
  IF n_gdpr <> 1 THEN
    RAISE EXCEPTION '000477: la persona del registro non è classificata ACTOR nel registro GDPR (%)', n_gdpr;
  END IF;
  RAISE NOTICE '000477 ok — registro delle scritture con persona e agente (L9, A-1)';
END;
$post$;

COMMIT;
