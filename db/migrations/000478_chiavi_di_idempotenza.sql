-- 000478_chiavi_di_idempotenza.sql
-- Piano interfacce, lotto L10, voce A-10 (riga «idempotenza delle scritture» della griglia V6):
-- «un agente che riprova non duplica».
--
-- Una richiesta di scrittura (POST, PUT, PATCH, DELETE su /v1/*) che porta l'intestazione
-- `Idempotency-Key` lascia qui la propria impronta e, finita, la risposta. Se la stessa persona
-- ripete la stessa chiave entro 24 ore:
--  - con la stessa richiesta (stesso metodo, rotta e corpo) riceve la risposta di allora, senza
--    che la scrittura si ripeta;
--  - con una richiesta diversa riceve 422 IDEMPOTENCY_KEY_REUSED;
--  - mentre la prima è ancora in corso riceve 409 IDEMPOTENCY_IN_PROGRESS.
-- Una risposta 5xx non si conserva: la riga si toglie e la richiesta si può ripetere.
--
-- La chiave appartiene a chi chiama (`user_id` dal token, mai dal corpo): due persone non si
-- vedono le chiavi. Un gettone d'agente vale come la persona per cui lavora, più l'agente: le
-- chiavi dell'agente non sono quelle della persona.
--
-- La risposta conservata può riguardare altre persone (è ciò che l'API ha risposto): per questo
-- la riga vive al più 24 ore, e nel registro GDPR è ACTOR e DELETE con conservazione di un
-- giorno. Senza chiave esterna, come audit.registro_scritture (000477).
--
-- Idempotente: CREATE ... IF NOT EXISTS, CREATE OR REPLACE, ON CONFLICT DO NOTHING.
-- Rollback dichiarato (elenco esplicito):
--   DELETE FROM sys.sys_gdpr_data_map WHERE (gdpr_map_table_schema, gdpr_map_table_name,
--     gdpr_map_subject_fk) = ('audit','chiavi_idempotenza','chiave_idempotenza_user_id');
--   DROP TABLE audit.chiavi_idempotenza;

BEGIN;

CREATE TABLE IF NOT EXISTS audit.chiavi_idempotenza (
  chiave_idempotenza_id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chiave_idempotenza_user_id       uuid         NOT NULL,
  chiave_idempotenza_agente        varchar(64)  NOT NULL DEFAULT '',
  chiave_idempotenza_chiave        varchar(128) NOT NULL,
  chiave_idempotenza_impronta      char(64)     NOT NULL,
  chiave_idempotenza_metodo        varchar(8)   NOT NULL,
  chiave_idempotenza_rotta         varchar(200) NOT NULL,
  chiave_idempotenza_stato         varchar(10)  NOT NULL DEFAULT 'in_corso',
  chiave_idempotenza_stato_http    smallint,
  chiave_idempotenza_tipo          varchar(100),
  chiave_idempotenza_corpo         text,
  chiave_idempotenza_creata_il     timestamptz  NOT NULL DEFAULT now(),
  chiave_idempotenza_scade_il      timestamptz  NOT NULL DEFAULT now() + interval '24 hours'
);

COMMENT ON TABLE audit.chiavi_idempotenza IS
  '000478 (piano interfacce L10, A-10) — una riga per Idempotency-Key di una scrittura su /v1/*: '
  'l''impronta della richiesta e, finita, la risposta da ripetere a chi riprova. Vive 24 ore.';

CREATE UNIQUE INDEX IF NOT EXISTS uq_chiavi_idempotenza_chiamante
  ON audit.chiavi_idempotenza (chiave_idempotenza_user_id, chiave_idempotenza_agente, chiave_idempotenza_chiave);
CREATE INDEX IF NOT EXISTS idx_chiavi_idempotenza_scadenza
  ON audit.chiavi_idempotenza (chiave_idempotenza_scade_il);

-- I vincoli fuori dal CREATE TABLE, in forma DROP/ADD: la catena si riapplica a ogni deploy.
ALTER TABLE audit.chiavi_idempotenza DROP CONSTRAINT IF EXISTS chiavi_idempotenza_stato_ck;
ALTER TABLE audit.chiavi_idempotenza ADD CONSTRAINT chiavi_idempotenza_stato_ck
  CHECK (
    (chiave_idempotenza_stato = 'in_corso' AND chiave_idempotenza_stato_http IS NULL)
    OR (chiave_idempotenza_stato = 'conclusa' AND chiave_idempotenza_stato_http BETWEEN 100 AND 499)
  );
ALTER TABLE audit.chiavi_idempotenza DROP CONSTRAINT IF EXISTS chiavi_idempotenza_metodo_ck;
ALTER TABLE audit.chiavi_idempotenza ADD CONSTRAINT chiavi_idempotenza_metodo_ck
  CHECK (chiave_idempotenza_metodo IN ('POST', 'PUT', 'PATCH', 'DELETE'));
ALTER TABLE audit.chiavi_idempotenza DROP CONSTRAINT IF EXISTS chiavi_idempotenza_chiave_ck;
ALTER TABLE audit.chiavi_idempotenza ADD CONSTRAINT chiavi_idempotenza_chiave_ck
  CHECK (length(chiave_idempotenza_chiave) BETWEEN 1 AND 128);
ALTER TABLE audit.chiavi_idempotenza DROP CONSTRAINT IF EXISTS chiavi_idempotenza_durata_ck;
ALTER TABLE audit.chiavi_idempotenza ADD CONSTRAINT chiavi_idempotenza_durata_ck
  CHECK (chiave_idempotenza_scade_il <= chiave_idempotenza_creata_il + interval '24 hours');

INSERT INTO sys.sys_gdpr_data_map (
  gdpr_map_table_schema, gdpr_map_table_name, gdpr_map_subject_fk,
  gdpr_map_data_class, gdpr_map_erasure_strategy, gdpr_map_reference_kind,
  gdpr_map_retention_days, gdpr_map_age_column, gdpr_map_legal_basis
) VALUES
  ('audit', 'chiavi_idempotenza', 'chiave_idempotenza_user_id',
   'OPERATIONAL', 'DELETE', 'ACTOR', 1, 'chiave_idempotenza_creata_il',
   'Chiave di idempotenza di una scrittura (L10, A-10): conserva per 24 ore la risposta da ripetere a '
   'chi riprova. La persona ne è autrice; la risposta può riguardare altri: fuori dal fascicolo art. 15.')
ON CONFLICT (gdpr_map_table_schema, gdpr_map_table_name, gdpr_map_subject_fk) DO NOTHING;

DO $post$
DECLARE
  n_ck int;
  n_gdpr int;
BEGIN
  SELECT count(*) INTO n_ck FROM pg_constraint
   WHERE conrelid = 'audit.chiavi_idempotenza'::regclass
     AND conname IN ('chiavi_idempotenza_stato_ck', 'chiavi_idempotenza_metodo_ck',
                     'chiavi_idempotenza_chiave_ck', 'chiavi_idempotenza_durata_ck');
  IF n_ck <> 4 THEN
    RAISE EXCEPTION '000478: vincoli delle chiavi di idempotenza % su 4', n_ck;
  END IF;
  SELECT count(*) INTO n_gdpr FROM sys.sys_gdpr_data_map
   WHERE gdpr_map_table_schema = 'audit' AND gdpr_map_table_name = 'chiavi_idempotenza'
     AND gdpr_map_erasure_strategy = 'DELETE' AND gdpr_map_reference_kind = 'ACTOR';
  IF n_gdpr <> 1 THEN
    RAISE EXCEPTION '000478: le chiavi di idempotenza non sono classificate nel registro GDPR (%)', n_gdpr;
  END IF;
  RAISE NOTICE '000478 ok — chiavi di idempotenza delle scritture (L10, A-10)';
END;
$post$;

COMMIT;
