#!/usr/bin/env node
/**
 * scripts/cowork-exchange/apply-pending.mjs
 *
 * CLI-side consumer of cowork_code_exchange/.cowork-pending-commits.json
 * per cowork_code_exchange/README.md v2.2 §-0 R6.
 *
 * Behavior:
 *   1. Read manifest, validate structure
 *   2. For each commit entry: git add <paths> + git commit -F <message_file>
 *   3. If manifest.push_after = true: git push <push_target>
 *   4. On success: rename manifest to .cowork-pending-commits/applied/<ts>.json
 *      and emit .inbox/cowork/pending/<ts>__pending-applied.md
 *   5. On failure: stop, leave manifest in place, emit a notification message
 *
 * Usage:
 *   node scripts/cowork-exchange/apply-pending.mjs [--dry-run] [--no-push]
 *
 * Exit codes:
 *   0   manifest applied successfully (or no manifest present = nothing to do)
 *   2   manifest invalid
 *   3   git operation failed
 *   4   push failed
 */

import { readFile, writeFile, rename, mkdir, readdir } from "node:fs/promises";
import { existsSync } from "node:fs";
import { join, resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { execSync } from "node:child_process";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const REPO_ROOT = resolve(__dirname, "..", "..");
const EXCHANGE_DIR = join(REPO_ROOT, "cowork_code_exchange");
const MANIFEST_PATH = join(EXCHANGE_DIR, ".cowork-pending-commits.json");
const MSGS_DIR = join(EXCHANGE_DIR, ".cowork-pending-commits");
const APPLIED_DIR = join(MSGS_DIR, "applied");

const args = process.argv.slice(2);
const DRY_RUN = args.includes("--dry-run");
const NO_PUSH = args.includes("--no-push");

function nowIso() {
  return new Date().toISOString().replace(/\.\d{3}Z$/, "Z");
}

function tsForFilename() {
  return nowIso().replace(/:/g, "-");
}

function logStep(msg) { console.log(`[apply-pending] ${msg}`); }
function logOk(msg)   { console.log(`[apply-pending] OK ${msg}`); }
function logErr(msg)  { console.error(`[apply-pending] ERROR ${msg}`); }

function runGit(argv, { allowFail = false } = {}) {
  const cmd = `git ${argv.join(" ")}`;
  logStep(`> ${cmd}`);
  if (DRY_RUN) { logStep(`(dry-run, skipped)`); return ""; }
  try {
    const out = execSync(cmd, { cwd: REPO_ROOT, encoding: "utf8", stdio: ["pipe", "pipe", "pipe"] });
    if (out.trim()) logStep(`  ${out.trim().split("\n").join("\n  ")}`);
    return out;
  } catch (e) {
    if (allowFail) return null;
    logErr(`git failed: ${e.stderr || e.message}`);
    throw e;
  }
}

async function emitNotification(kind, manifest, opts = {}) {
  // Best-effort emission of an inbox message to Cowork
  const ts = tsForFilename();
  const dir = join(EXCHANGE_DIR, ".inbox", "cowork", "pending");
  await mkdir(dir, { recursive: true });
  const goal = manifest.related_goal || "000";
  const filename = `${ts}__${goal}__${kind}.md`;
  const ref = "cowork_code_exchange/.cowork-pending-commits.json";

  const body = opts.body || `Manifest ${manifest.generated_at} applied by CLI at ${nowIso()}. ${opts.detail || ""}`;
  const content = `---
from: cli
to: cowork
goal_id: ${goal}
slug: pending-applied
kind: ${kind}
ref_files:
  - ${ref}
created_at: ${nowIso()}
read_at: null
acknowledged_by: null
expected_response_kind: ack
expected_response_by: null
---

# ${kind === "pending_applied" ? "Manifest applied" : "Manifest application failed"} — ${manifest.generated_at}

${body}
`;
  await writeFile(join(dir, filename), content, "utf8");
  logOk(`notification emitted: cowork/pending/${filename}`);
}

async function main() {
  if (!existsSync(MANIFEST_PATH)) {
    logStep(`no manifest at ${MANIFEST_PATH} — nothing to do`);
    process.exit(0);
  }

  let manifest;
  try {
    manifest = JSON.parse(await readFile(MANIFEST_PATH, "utf8"));
  } catch (e) {
    logErr(`manifest is not valid JSON: ${e.message}`);
    process.exit(2);
  }

  if (!Array.isArray(manifest.commits) || manifest.commits.length === 0) {
    logErr(`manifest.commits is empty or missing`);
    process.exit(2);
  }

  logStep(`manifest generated by ${manifest.generated_by} at ${manifest.generated_at}`);
  logStep(`commits to apply: ${manifest.commits.length}`);

  // Pre-flight: clean a stale .git/index.lock (max safety; only delete if older than 5 min)
  const lockPath = join(REPO_ROOT, ".git", "index.lock");
  if (existsSync(lockPath)) {
    const { mtimeMs } = await import("node:fs").then((m) => m.statSync(lockPath));
    const ageMin = (Date.now() - mtimeMs) / 60000;
    if (ageMin > 5) {
      logStep(`stale .git/index.lock (${ageMin.toFixed(1)}min old) — removing`);
      try { await import("node:fs").then((m) => m.unlinkSync(lockPath)); }
      catch (e) { logErr(`could not remove stale lock: ${e.message}`); }
    }
  }

  let appliedCount = 0;
  for (let i = 0; i < manifest.commits.length; i++) {
    const c = manifest.commits[i];
    const idx = i + 1;
    logStep(`---- commit ${idx}/${manifest.commits.length}: ${c.title} ----`);

    // Stage paths
    if (!Array.isArray(c.paths) || c.paths.length === 0) {
      logErr(`commit ${idx} has no paths`);
      continue;
    }
    for (const p of c.paths) {
      runGit(["add", "--", p]);
    }

    // Check if anything is actually staged
    const staged = runGit(["diff", "--cached", "--name-only"], { allowFail: true }) || "";
    if (!staged.trim()) {
      logStep(`nothing staged after add (already in HEAD or files absent) — skipping commit ${idx}`);
      continue;
    }

    // Determine message file
    const msgPath = c.message_file
      ? join(EXCHANGE_DIR, c.message_file)
      : null;
    let msgArg = "";
    if (msgPath && existsSync(msgPath)) {
      msgArg = `-F "${msgPath}"`;
    } else if (c.message) {
      // inline message
      const tmpMsg = join(MSGS_DIR, `_inline-msg-${idx}.txt`);
      await mkdir(MSGS_DIR, { recursive: true });
      await writeFile(tmpMsg, c.message, "utf8");
      msgArg = `-F "${tmpMsg}"`;
    } else {
      logErr(`commit ${idx} has no message_file and no message — aborting`);
      await emitNotification("pending_apply_failed", manifest, { detail: `commit ${idx} (${c.title}) missing message` });
      process.exit(3);
    }

    runGit(["commit", msgArg]);
    appliedCount++;
  }

  // Push if requested
  if (manifest.push_after && !NO_PUSH) {
    const target = manifest.push_target || "origin/main";
    const [remote, branch] = target.includes("/") ? target.split("/") : ["origin", target];
    logStep(`---- push to ${target} ----`);
    try {
      runGit(["push", remote, branch]);
    } catch (e) {
      await emitNotification("pending_apply_failed", manifest, { detail: `push to ${target} failed` });
      process.exit(4);
    }
  } else if (manifest.push_after && NO_PUSH) {
    logStep(`(--no-push specified; commits applied locally only)`);
  }

  // Archive manifest
  await mkdir(APPLIED_DIR, { recursive: true });
  const archivedAt = tsForFilename();
  const archivedPath = join(APPLIED_DIR, `${archivedAt}_manifest.json`);
  if (!DRY_RUN) {
    await rename(MANIFEST_PATH, archivedPath);
    logOk(`manifest archived: ${archivedPath.replace(REPO_ROOT, "<repo>")}`);
  }

  // Emit notification
  await emitNotification("pending_applied", manifest, {
    detail: `${appliedCount}/${manifest.commits.length} commits applied${manifest.push_after && !NO_PUSH ? " + pushed" : ""}.`,
  });

  logOk(`done. ${appliedCount} commits applied${manifest.push_after && !NO_PUSH ? " + pushed" : ""}.`);
}

main().catch((e) => {
  console.error("apply-pending crashed:", e.message);
  process.exit(1);
});
